num1 = int(input("Enter an integer number: "))
num2 = float(input("Enter a decimal (float) number: "))
 
addition = num1 + num2
multiplication = num1 * num2
 
print("\n----- Results -----")
print(num1, "+", num2, "=", addition)
print(num1, "*", num2, "=", multiplication)
